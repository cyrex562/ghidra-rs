    fn test_apply_to_success() {
        let cmd = TestCommand {
            name: "test_cmd".to_string(),
            can_apply_result: true,
            apply_result: true,
        };
        let program = MockProgram;
        let monitor = MockTaskMonitor;
        let result = cmd.apply_to(&program, &monitor);
        assert!(result.is_ok());
        assert!(result.unwrap());
    }

