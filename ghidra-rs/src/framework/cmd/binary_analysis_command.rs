/// A command that can be applied to a binary analysis program.
///
/// NOTE: All implementations of `BinaryAnalysisCommand` must end with "BinaryAnalysisCommand" in
/// their type name. The class searcher will not find implementations that do not follow this naming
/// convention.
///
/// This trait represents a single analysis operation that can be applied to a `Program`. The
/// command encapsulates analysis logic and provides information about whether it can be applied
/// to a given program and the status of the analysis after application.
pub trait BinaryAnalysisCommand: ExtensionPoint + Send + Sync {
    /// Determines if this command can be applied to the given program.
    ///
    /// # Arguments
    ///
    /// * `program` - The program to inspect.
    ///
    /// # Returns
    ///
    /// `true` if this command can be applied to the given program, `false` otherwise.
    fn can_apply(&self, program: &dyn Program) -> bool;

    /// Applies this command to the given program.
    ///
    /// # Arguments
    ///
    /// * `program` - The program to apply this command to.
    /// * `monitor` - A task monitor for tracking progress and checking for cancellation.
    ///
    /// # Returns
    ///
    /// `true` if the command applied successfully, `false` otherwise.
    ///
    /// # Errors
    ///
    /// May return an error if something goes wrong during execution.
    fn apply_to(
        &self,
        program: &dyn Program,
        monitor: &dyn TaskMonitor,
    ) -> Result<bool, Box<dyn std::error::Error>>;

    /// Gets the messages generated by this command.
    ///
    /// # Returns
    ///
    /// A message log containing any messages generated during command execution. Returns `None`
    /// if no messages were generated.
    fn get_messages(&self) -> Option<Box<dyn MessageLog>>;

    /// Gets the name of this command.
    ///
    /// # Returns
    ///
    /// The display name of this command.
    fn get_name(&self) -> String;
}

