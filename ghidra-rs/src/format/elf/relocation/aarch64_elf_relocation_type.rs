#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn none_has_type_id_zero() {
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_NONE.type_id(), 0);
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_NONE.name(), "R_AARCH64_NONE");
    }

    #[test]
    fn basic_data_relocations_match_java_ids() {
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_ABS64.type_id(), 257);
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_ABS32.type_id(), 258);
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_PREL16.type_id(), 262);
    }

    #[test]
    fn aliased_tls_constants_share_type_id() {
        // R_AARCH64_TLS_DTPMOD64/DTPREL64/TPREL64 alias R_AARCH64_TLS_DTPMOD/DTPREL/TPREL in Java.
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_TLS_DTPMOD64.type_id(), 1028);
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_TLS_DTPREL64.type_id(), 1029);
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_TLS_TPREL64.type_id(), 1030);
    }

    #[test]
    fn last_variant_matches_java_max_id() {
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_IRELATIVE.type_id(), 1032);
        assert_eq!(Aarch64ElfRelocationType::R_AARCH64_IRELATIVE.name(), "R_AARCH64_IRELATIVE");
    }

    #[test]
    fn implements_elf_relocation_type_trait_object() {
        let r: &dyn ElfRelocationType = &Aarch64ElfRelocationType::R_AARCH64_JUMP_SLOT;
        assert_eq!(r.type_id(), 1026);
        assert_eq!(r.name(), "R_AARCH64_JUMP_SLOT");
    }
}
