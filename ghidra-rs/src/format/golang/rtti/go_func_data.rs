    /// Builds a `GoFuncData` whose `FUNCDATA_ArgInfo` entry points at `arg_info` bytes.
    fn func_data_with_arg_info(arg_info: Vec<u8>) -> GoFuncData {
        // npcdata = 0, so funcdata[5] reads from field offset 40 + 4*5 = 60.
        let context = context_at(0x1000, 40);
        context.field_readers.lock().unwrap().insert(60, vec![0x00, 0x00, 0x00, 0x00]);
        let mut readers = HashMap::new();
        readers.insert(0x9000, arg_info);
        let mapper = MockGoRttiMapper {
            moduledata: Some(MockModuleData {
                gofunc: 0x9000,
                funcnametab: moduledata_named("main.foo").funcnametab,
                ..Default::default()
            }),
            readers,
        };
        let mut f = func_data(mapper, context);
        f.nfuncdata = 8;
        f
    }

    #[test]
    fn recovered_signature_reads_two_primitive_args() {
        // 0x00 'offset' then size 8, twice, then ENDSEQ.
        let f = func_data_with_arg_info(vec![0x00, 0x08, 0x00, 0x08, 0xff]);
        assert_eq!(f.recover_function_signature().unwrap(), "func main.foo(8, 8) ???");
    }

    #[test]
    fn recovered_signature_groups_an_aggregate() {
        // STARTAGG, two 4-byte args, ENDAGG, one 8-byte arg, ENDSEQ.
        let f = func_data_with_arg_info(vec![
            0xfe, 0x00, 0x04, 0x00, 0x04, 0xfd, 0x00, 0x08, 0xff,
        ]);
        assert_eq!(
            f.recover_function_signature().unwrap(),
            "func main.foo(struct? {4, 4}, 8) ???"
        );
    }

    #[test]
    fn recovered_signature_flags_dotdotdot_as_partial() {
        let f = func_data_with_arg_info(vec![0x00, 0x08, 0xfc, 0xff]);
        assert_eq!(
            f.recover_function_signature().unwrap(),
            "[partial] func main.foo(8, ...) ???"
        );
    }

    #[test]
    fn recovered_signature_flags_too_large_offset_as_partial() {
        let f = func_data_with_arg_info(vec![0xfb, 0xff]);
        assert_eq!(f.recover_function_signature().unwrap(), "[partial] func main.foo(???) ???");
    }

    #[test]
    fn recovered_signature_flags_truncated_data_as_error() {
        // Runs off the end of the reader before ENDSEQ. Java sets the error flag on the top-level
        // RecoveredArg, and `hasPartialFlag()` reads that same field, so both markers appear.
        let f = func_data_with_arg_info(vec![0x00, 0x08]);
        assert_eq!(
            f.recover_function_signature().unwrap(),
            "[partial] [error] func main.foo(8) ???"
        );
    }

