    /// Deterministic stand-in for a pctab evaluator: replays a canned `(value, pc)` script.
    struct MockPcValueEvaluator {
        func_entry: i64,
        /// `(value, pc)` pairs, consumed in order by each `step`.
        script: Vec<(i32, i64)>,
        pos: usize,
        value: i32,
        pc: i64,
    }

    impl MockPcValueEvaluator {
        fn new(func_entry: i64, script: Vec<(i32, i64)>) -> Self {
            Self { func_entry, script, pos: 0, value: -1, pc: func_entry }
        }

        fn step(&mut self) -> bool {
            match self.script.get(self.pos) {
                Some(&(value, pc)) => {
                    self.pos += 1;
                    self.value = value;
                    self.pc = pc;
                    true
                }
                None => false,
            }
        }
    }

    impl GoPcValueEvaluator for MockPcValueEvaluator {
        fn get_pc(&self) -> i64 {
            self.pc
        }
        fn reset(&mut self) {
            self.pos = 0;
            self.value = -1;
            self.pc = self.func_entry;
        }
        fn get_max_pc(&mut self) -> std::io::Result<i64> {
            self.eval(i64::MAX)?;
            Ok(self.pc)
        }
        fn eval(&mut self, target_pc: i64) -> std::io::Result<i32> {
            while self.pc <= target_pc {
                if !self.step() {
                    return Ok(-1);
                }
            }
            Ok(self.value)
        }
        fn eval_next(&mut self) -> std::io::Result<i32> {
            let pc = self.pc;
            self.eval(pc)
        }
        fn eval_all(&mut self, target_pc: i64) -> std::io::Result<Vec<i32>> {
            let mut result = Vec::new();
            while self.pc <= target_pc {
                if !self.step() {
                    return Ok(result);
                }
                result.push(self.value);
            }
            Ok(result)
        }
        fn markup(&mut self, _session: &dyn MarkupSession) -> std::io::Result<()> {
            Ok(())
        }
    }

