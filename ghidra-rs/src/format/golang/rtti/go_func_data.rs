/// `NumericUtilities.MAX_UNSIGNED_INT32_AS_LONG`; `ghidra.util.NumericUtilities` is not ported
/// yet and this is the only constant [`GoFuncData`] needs from it.
const MAX_UNSIGNED_INT32_AS_LONG: i64 = 0xffff_ffff;

/// Size in bytes of one entry in the pcdata/funcdata `int32[]` arrays that trail the structure.
const PC_DATA_ENTRY_SIZE: i64 = 4;

/// A structure that Go generates that contains metadata about a function.
///
/// Mirrors Ghidra's `runtime._func` structure mapping (Java `GoFuncData`).
///
/// The numeric fields are `pub` rather than hidden behind getter/setter pairs because Java
/// populates them by reflection during structure deserialization; [`set_entryoff`] and
/// [`set_entry`] remain methods because Java's deserializer calls them for their side effect of
/// computing [`func_address`](Self::get_func_address).
///
/// [`set_entryoff`]: Self::set_entryoff
/// [`set_entry`]: Self::set_entry
pub struct GoFuncData {
    /// `@ContextField` injected Go binary context (Java field `programContext`).
    program_context: Box<dyn GoRttiMapper>,
    /// `@ContextField` injected structure-read context (Java field `context`).
    context: Box<dyn StructureContext<GoFuncData>>,
    /// Relative offset of the function; present in Go 1.18+ (Java field `entryoff`).
    pub entryoff: i64,
    /// Absolute location of the function; present up to Go 1.17 (Java field `entry`).
    pub entry: i64,
    /// Offset of the function's name string, a `uint32` (Java field `nameoff`).
    pub nameoff: i64,
    /// Offset of the function's `deferreturn` call site (Java field `deferreturn`).
    pub deferreturn: i64,
    /// Offset in `moduledata.pctab` where file info starts (Java field `pcfile`).
    pub pcfile: i64,
    /// Offset in `moduledata.pctab` where line-number info starts (Java field `pcln`).
    pub pcln: i64,
    /// Offset in `moduledata.pctab` of the stack-pointer table; `int32` up to 1.15, `uint32`
    /// from 1.16 (Java field `pcsp`).
    pub pcsp: i64,
    /// Number of elements in the varlen pcdata array (Java field `npcdata`).
    pub npcdata: i32,
    /// Compilation-unit offset into `moduledata.cutab`; present in Go 1.16+, defaults to -1
    /// (Java field `cuOffset`).
    pub cu_offset: i64,
    /// `runtime.funcID` of this function (Java field `funcID`).
    pub func_id: i8,
    /// `runtime.funcFlag` bits; present in Go 1.17+, see [`GoFuncFlag`] (Java field `flag`).
    pub flag: i8,
    /// Number of elements in the varlen funcdata array (Java field `nfuncdata`).
    pub nfuncdata: i32,

    /// Set when `entryoff` or `entry` are set (Java field `funcAddress`).
    func_address: Option<Address>,
    /// Set by [`set_func_address_override`](Self::set_func_address_override) (Java field
    /// `funcAddressOverride`).
    func_address_override: bool,
}

impl GoFuncData {
    /// Creates an instance with every mapped field at its Java default (`cuOffset` starts at -1,
    /// mirroring the Java field initializer). Deserialization then fills the fields in, calling
    /// [`set_entryoff`](Self::set_entryoff) or [`set_entry`](Self::set_entry) for the entry point.
    pub fn new(
        program_context: Box<dyn GoRttiMapper>,
        context: Box<dyn StructureContext<GoFuncData>>,
    ) -> Self {
        Self {
            program_context,
            context,
            entryoff: 0,
            entry: 0,
            nameoff: 0,
            deferreturn: 0,
            pcfile: 0,
            pcln: 0,
            pcsp: 0,
            npcdata: 0,
            cu_offset: -1,
            func_id: 0,
            flag: 0,
            nfuncdata: 0,
            func_address: None,
            func_address_override: false,
        }
    }

    /// Sets the function's entry point via a relative offset value.
    ///
    /// Called via deserialization for the `entryoff` field mapping annotation.
    ///
    /// An offset that runs off the end of the moduledata's text address space yields no address,
    /// the same outcome as a missing moduledata (Java lets `Address.add` throw here instead).
    pub fn set_entryoff(&mut self, entryoff: i64) {
        self.entryoff = entryoff;

        self.func_address = self
            .get_moduledata()
            .and_then(|moduledata| moduledata.get_text().add(entryoff).ok());
        self.entry = self.func_address.as_ref().map_or(-1, Address::offset);
    }

    /// Sets the absolute entry address.
    ///
    /// Called via deserialization for the `entry` field mapping annotation. Java reaches the code
    /// address through `context.getDataTypeMapper()`, which is this same `GoRttiMapper`.
    pub fn set_entry(&mut self, entry: i64) {
        self.entry = entry;
        self.func_address = Some(self.program_context.get_code_address(entry));
    }

    /// Overrides the address this function is reported at, flagging it as overridden for
    /// [`get_description`](Self::get_description).
    pub fn set_func_address_override(&mut self, addr: Address) {
        self.func_address = Some(addr);
        self.func_address_override = true;
    }

    /// Returns the address of this function, if one has been established.
    pub fn get_func_address(&self) -> Option<&Address> {
        self.func_address.as_ref()
    }

    /// Returns the address range of this function's body, recovered by examining addresses in the
    /// function's pc-to-filename translation table, or, if not present, a single address range
    /// that contains the function's entry point.
    ///
    /// Returns `None` when this function has no address at all (Java throws an NPE instead).
    pub fn get_body(&self) -> Option<AddressRange> {
        let func_address = self.func_address.as_ref()?;

        // find the body of a function by looking at its pc-to-filename translation table and
        // using the max pc value
        let max_pc = self
            .new_pc_value_evaluator(self.pcfile)
            .and_then(|mut eval| eval.get_max_pc());
        if let Ok(max_pc) = max_pc {
            let max = max_pc - 1;
            if max > self.entry {
                return Some(AddressRange::new(
                    func_address.clone(),
                    func_address.space().address(max),
                ));
            }
        }
        // fall thru, return 1-byte range
        Some(AddressRange::new(func_address.clone(), func_address.clone()))
    }

    /// Returns the Ghidra function that corresponds to this Go function, or `None` if there is no
    /// Ghidra function at the address.
    pub fn get_function(&self) -> Option<Arc<dyn Function>> {
        self.program_context.get_function_at(self.get_func_address()?)
    }

    /// Returns the address of this function's `deferreturn` call site, or `None` if it has none.
    pub fn get_deferreturn_address(&self) -> Option<Address> {
        if self.deferreturn == 0 {
            return None;
        }
        self.get_func_address()?.add(self.deferreturn).ok()
    }

    fn get_pc_data_start_offset(&self, table_index: i32) -> i64 {
        self.context.get_structure_length() as i64 + PC_DATA_ENTRY_SIZE * table_index as i64
    }

    fn get_pc_data_start(&self, table_index: i32) -> std::io::Result<i64> {
        let mut reader = self.context.get_field_reader(self.get_pc_data_start_offset(table_index));
        Ok(reader.read_next_unsigned_int()? as i64)
    }

    fn get_func_data_ptr(&self, table_index: i32) -> std::io::Result<i64> {
        // hacky, since both pcdata and funcdata are sequential int32[] arrays, just reuse logic
        // for first one to index into second one
        self.get_pc_data_start(self.npcdata + table_index)
    }

    /// Stands in for `new GoPcValueEvaluator(this, offset)`; the evaluator is constructed by the
    /// moduledata (see [`GoModuledata::new_pc_value_evaluator`]) so that the unported evaluator
    /// does not have to name `GoFuncData`. Java throws an NPE where this returns an error.
    fn new_pc_value_evaluator(&self, offset: i64) -> std::io::Result<Box<dyn GoPcValueEvaluator>> {
        let moduledata = self.get_moduledata().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::NotFound,
                "no moduledata contains this GoFuncData",
            )
        })?;
        let func_entry = self
            .func_address
            .as_ref()
            .ok_or_else(|| {
                std::io::Error::new(std::io::ErrorKind::InvalidData, "GoFuncData has no address")
            })?
            .offset();
        moduledata.new_pc_value_evaluator(offset, func_entry)
    }

    /// Returns the address in the moduledata's `pctab` where this function's file info starts.
    pub fn get_pcfile_ref_address(&self) -> Option<Address> {
        self.get_pctab_element_address(self.pcfile)
    }

    /// Returns the address in the moduledata's `pctab` where this function's line info starts.
    pub fn get_pcln_ref_address(&self) -> Option<Address> {
        self.get_pctab_element_address(self.pcln)
    }

    /// Returns the address in the moduledata's `pctab` where this function's stack-pointer info
    /// starts.
    pub fn get_pcspref_address(&self) -> Option<Address> {
        self.get_pctab_element_address(self.pcsp)
    }

    fn get_pctab_element_address(&self, pctab_offset: i64) -> Option<Address> {
        let pctab = self.get_moduledata()?.get_pctab()?;
        Some(self.program_context.get_data_address(pctab.get_element_offset(1, pctab_offset)))
    }

    /// Returns a value from the specified pc->value lookup table, for a specific address (that
    /// should be within the function's footprint).
    ///
    /// The returned int is specific to the [table](GoPcDataTable) it comes from, or -1 if the
    /// requested table index is not present for this function.
    pub fn get_pc_data_value(
        &self,
        table_index: GoPcDataTable,
        target_pc: i64,
    ) -> std::io::Result<i32> {
        if table_index.index() as i32 >= self.npcdata {
            return Ok(-1);
        }
        let pcstart = self.get_pc_data_start(table_index.index() as i32)?;
        self.new_pc_value_evaluator(pcstart)?.eval(target_pc)
    }

    /// Returns all values for the specified pc->value lookup table for the entire range of the
    /// function's footprint, or an empty list if the requested table index is not present for
    /// this function.
    pub fn get_pc_data_values(&self, table_index: GoPcDataTable) -> std::io::Result<Vec<i32>> {
        if table_index.index() as i32 >= self.npcdata {
            return Ok(Vec::new());
        }
        let pcstart = self.get_pc_data_start(table_index.index() as i32)?;
        self.new_pc_value_evaluator(pcstart)?.eval_all(i64::MAX)
    }

    /// Returns a value associated with this function, or -1 if the requested table index is not
    /// present for this function.
    ///
    /// Java returns `null` (auto-unboxed, so really an NPE) when the funcdata pointer itself reads
    /// back as -1; this returns -1 there, matching the method's documented "not present" contract.
    pub fn get_func_data_value(&self, table_index: GoFuncDataTable) -> std::io::Result<i64> {
        if table_index.index() as i32 >= self.nfuncdata {
            return Ok(-1);
        }
        let gofuncoffset = self.get_moduledata().map_or(0, |moduledata| moduledata.get_gofunc());
        if gofuncoffset == 0 {
            return Ok(-1);
        }
        let off = self.get_func_data_ptr(table_index.index() as i32)?;
        Ok(if off == -1 { -1 } else { gofuncoffset + off })
    }

    /// Attempts to build a 'function signature' string representing the known information about
    /// this function's arguments, using Go's built-in stack trace metadata.
    ///
    /// The information that can be recovered about arguments is limited to the size of the
    /// argument and the general grouping (e.g. grouping of arg values as a structure or array).
    /// Return value information is unknown and always represented as an "undefined" data type.
    ///
    /// Returns a pseudo-function signature string, such as `"undefined foo( 8, 8 )"`, which would
    /// indicate the function had 2 8-byte arguments.
    pub fn recover_function_signature(&self) -> std::io::Result<String> {
        let sig = RecoveredSignature::read(self, self.program_context.as_ref())?;
        Ok(sig.to_string())
    }

    /// Returns the address of this function's name string.
    ///
    /// Referenced from `nameoff`'s markup annotation.
    pub fn get_name_address(&self) -> Option<Address> {
        let moduledata = self.get_moduledata()?;
        let slice = moduledata.get_funcnametab().or_else(|| moduledata.get_pclntable())?;
        slice.get_array_address().add(self.nameoff).ok()
    }

    /// Returns the name of this function, falling back to a synthesized `unknown_func_*` name if
    /// the name string cannot be read.
    pub fn get_name(&self) -> String {
        if let Some(moduledata) = self.get_moduledata() {
            if let Some(slice) =
                moduledata.get_funcnametab().or_else(|| moduledata.get_pclntable())
            {
                let mut reader = slice.get_element_reader(1, self.nameoff as i32);
                if let Ok(name) = reader.read_next_utf8_string() {
                    return name;
                }
                // fall thru
            }
        }
        format!(
            "unknown_func_{:x}_{}",
            self.context.get_structure_start(),
            self.func_address
                .as_ref()
                .map_or_else(|| "missing_addr".to_string(), Address::to_string)
        )
    }

    /// Returns the name of this function, as a parsed `GoSymbolName` symbol object.
    pub fn get_symbol_name(&self) -> Box<dyn GoSymbolName> {
        self.program_context.parse_symbol_name(&self.get_name())
    }

    /// Returns a descriptive string.
    ///
    /// Referenced from the `entry`/`entryoff` fields' markup annotations.
    pub fn get_description(&self) -> String {
        format!(
            "{}@{}{}",
            self.get_name(),
            self.func_address.as_ref().map_or_else(|| "null".to_string(), Address::to_string),
            if self.func_address_override { " (overridden)" } else { "" }
        )
    }

    /// Returns `true` if this function is inline.
    pub fn is_inline(&self) -> bool {
        self.entryoff == -1 || self.entryoff == MAX_UNSIGNED_INT32_AS_LONG
    }

    /// Returns the [`GoFuncFlag`] func flags for this function.
    pub fn get_flags(&self) -> Vec<GoFuncFlag> {
        GoFuncFlag::parse_flags(self.flag_bits())
    }

    /// Returns `true` if this function is an ASM function.
    pub fn is_asm_function(&self) -> bool {
        GoFuncFlag::Asm.is_set(self.flag_bits())
    }

    fn flag_bits(&self) -> u32 {
        self.flag as u8 as u32
    }

    /// Returns information about the source file that this function was defined in, or `None` if
    /// no source file info is present.
    pub fn get_source_file_info(&self) -> std::io::Result<Option<GoSourceFileInfo>> {
        if self.get_moduledata().is_none() {
            return Ok(None);
        }
        let fileno = self.new_pc_value_evaluator(self.pcfile)?.eval(self.entry)?;
        let line_num = self.new_pc_value_evaluator(self.pcln)?.eval(self.entry)?;

        if fileno < 0 {
            return Ok(None);
        }

        Ok(self
            .get_source_filename(fileno)?
            .map(|file_name| GoSourceFileInfo::new(file_name, line_num)))
    }

    /// Walks this function's pc->file and pc->line tables and records the resulting source map
    /// entries in the program.
    ///
    /// Errors are logged and give up on the rest of the walk, as in Java.
    pub fn markup_source_file_info(&self) {
        if self.get_moduledata().is_none() {
            return;
        }

        let result: std::io::Result<()> = (|| {
            let mut file_eval = self.new_pc_value_evaluator(self.pcfile)?;
            let mut line_eval = self.new_pc_value_evaluator(self.pcln)?;

            let mut startpc = self.entry;
            let mut prev_filenum: i32 = -1;
            loop {
                let line_num = line_eval.eval_next()?;
                if line_num <= 0 {
                    break;
                }
                let file_num = file_eval.eval(startpc)?;
                if file_num < 0 {
                    break;
                }
                file_eval.reset();

                if file_num != prev_filenum {
                    prev_filenum = file_num;
                    // Java passes a null filename through to `new SourceFile(null)`; skipping is
                    // the same intent as the "no value" check inside `get_source_filename`.
                    if let Some(file_name) = self.get_source_filename(file_num)? {
                        if file_name != GOLANG_AUTOGENERATED_FILENAME {
                            let file_name = normalize_native_path(&file_name);

                            let start_addr = self.program_context.get_code_address(startpc);
                            let len = line_eval.get_pc() - startpc;

                            self.add_source_map_entry(&file_name, line_num, &start_addr, len);
                        }
                    }
                }
                startpc = line_eval.get_pc();
            }
            Ok(())
        })();

        if let Err(e) = result {
            Msg::error_with_error("GoFuncData", &"Failed to set source file info", &e);
        }
    }

    /// Records one source map entry, logging (rather than propagating) a rejected path or address
    /// range, mirroring the Java `AddressOverflowException | IllegalArgumentException` catch.
    fn add_source_map_entry(
        &self,
        file_name: &str,
        line_num: i32,
        start_addr: &Address,
        len: i64,
    ) {
        let source_file = match SourceFile::new(file_name) {
            Ok(source_file) => source_file,
            Err(e) => {
                Msg::error("GoFuncData", &format!("Failed to add source file mapping: {}", e));
                return;
            }
        };
        let added = self
            .program_context
            .add_source_file(&source_file)
            .and_then(|()| {
                self.program_context.add_source_map_entry(&source_file, line_num, start_addr, len)
            });
        if let Err(e) = added {
            Msg::error("GoFuncData", &format!("Failed to add source file mapping: {}", e));
        }
    }

    fn get_source_filename(&self, fileno: i32) -> std::io::Result<Option<String>> {
        let moduledata = self.get_moduledata().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::NotFound,
                "no moduledata contains this GoFuncData",
            )
        })?;
        let missing = |what: &str| {
            std::io::Error::new(
                std::io::ErrorKind::NotFound,
                format!("moduledata has no {} slice", what),
            )
        };
        let filetab = moduledata.get_filetab();
        let (fileoff, name_slice) = match moduledata.get_cutab() {
            // when <= 1.15
            None => (
                filetab.ok_or_else(|| missing("filetab"))?.read_u_int_element(4, fileno)?,
                moduledata.get_pclntable().ok_or_else(|| missing("pclntable"))?,
            ),
            // when >= 1.16
            Some(cutab) => (
                cutab.read_u_int_element(4, self.cu_offset as i32 + fileno)?,
                filetab.ok_or_else(|| missing("filetab"))?,
            ),
        };
        if fileoff < 0 {
            // -1 == no value
            return Ok(None);
        }
        let mut reader = name_slice.get_element_reader(1, fileoff as i32);
        Ok(Some(reader.read_next_utf8_string()?))
    }

    /// Returns the `GoModuledata` that contains this function, if any.
    pub fn get_moduledata(&self) -> Option<Box<dyn GoModuledata>> {
        self.program_context
            .find_containing_module_by_func_data(self.context.get_structure_start())
    }
}

impl StructureMarkup<GoFuncData> for GoFuncData {
    fn structure_context(&self) -> &dyn StructureContext<GoFuncData> {
        self.context.as_ref()
    }

    fn structure_name(&self) -> std::io::Result<Option<String>> {
        Ok(Some(self.get_symbol_name().as_string()))
    }

    fn structure_namespace(&self) -> std::io::Result<Option<String>> {
        Ok(self.get_symbol_name().package_path())
    }

    fn structure_label(&self) -> std::io::Result<Option<String>> {
        Ok(Some(format!("{}___funcdata", self.structure_name()?.unwrap_or_default())))
    }

    fn additional_markup(
        &self,
        session: &dyn MarkupSession,
    ) -> Result<(), Box<dyn std::error::Error>> {
        let go_types = self.program_context.get_go_types();
        if self.npcdata > 0 {
            let uint32_dt = go_types.get_data_type("uint32")?;
            let pcdata_array_dt =
                self.program_context.new_array_data_type(uint32_dt.as_ref(), self.npcdata);
            let addr = self.context.get_structure_address().add(self.get_pc_data_start_offset(0))?;
            session.markup_address(addr.clone(), pcdata_array_dt.as_ref())?;
            session.label_address_in_namespace(
                addr,
                &format!("{}___pcdata", self.structure_label()?.unwrap_or_default()),
                &self.structure_namespace()?.unwrap_or_default(),
            )?;
        }
        if self.nfuncdata > 0 {
            let uint32_dt = go_types.get_data_type("uint32")?;
            let funcdata_array_dt =
                self.program_context.new_array_data_type(uint32_dt.as_ref(), self.nfuncdata);
            let addr = self
                .context
                .get_structure_address()
                .add(self.get_pc_data_start_offset(self.npcdata))?;
            session.markup_address(addr.clone(), funcdata_array_dt.as_ref())?;
            session.label_address_in_namespace(
                addr,
                &format!("{}___array", self.structure_label()?.unwrap_or_default()),
                &self.structure_namespace()?.unwrap_or_default(),
            )?;
        }
        if let Some(deferreturn_addr) = self.get_deferreturn_address() {
            let func_name = self.get_symbol_name();
            session.label_address_in_namespace(
                deferreturn_addr,
                &format!("{}_deferreturn", func_name.as_string()),
                &func_name.package_path().unwrap_or_default(),
            )?;
        }

        // errors marking up the pc-value tables are ignored, as in Java
        let _: std::io::Result<()> = (|| {
            self.new_pc_value_evaluator(self.pcfile)?.markup(session)?;
            self.new_pc_value_evaluator(self.pcln)?.markup(session)?;
            self.new_pc_value_evaluator(self.pcsp)?.markup(session)?;
            Ok(())
        })();

        Ok(())
    }
}

impl std::fmt::Display for GoFuncData {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "GoFuncData [getFuncAddress()={}, getSymbolName()={}, getStructureContext()={}]",
            self.func_address.as_ref().map_or_else(|| "null".to_string(), Address::to_string),
            self.get_symbol_name().as_string(),
            self.context.to_string()
        )
    }
}

/// Represents the information recovered about a single argument.
///
/// Mirrors the Java `GoFuncData.RecoveredArg` record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecoveredArg {
    /// List of components if this arg is an aggregate, otherwise `None`.
    pub sub_args: Option<Vec<RecoveredArg>>,
    /// Size of this arg if it is primitive.
    pub arg_size: i32,
    /// If `true`, this arg was marked as a `"..."` or `"_"` arg.
    pub partial: bool,
}

impl RecoveredArg {
    fn has_partial_flag(&self) -> bool {
        self.partial
            || self
                .sub_args
                .as_ref()
                .is_some_and(|sub_args| sub_args.iter().any(RecoveredArg::has_partial_flag))
    }

    fn concat_string(&self, sb: &mut String) {
        match &self.sub_args {
            Some(sub_args) => {
                sb.push_str("struct? {");
                for (i, sub_arg) in sub_args.iter().enumerate() {
                    if i != 0 {
                        sb.push_str(", ");
                    }
                    sub_arg.concat_string(sb);
                }
                sb.push('}');
            }
            None => match self.arg_size {
                -1 => sb.push_str("..."),
                -2 => sb.push_str("???"),
                arg_size => sb.push_str(&arg_size.to_string()),
            },
        }
    }
}

/// Represents approximate parameter signatures for a function.
///
/// Go's exception/stack-trace metadata is mined to provide these approximate signatures, and any
/// limitation in the information recovered is due to what Go stores. Instead of data types, only
/// the size and limited grouping of structure/array parameters is recoverable.
///
/// Mirrors the Java `GoFuncData.RecoveredSignature` record.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RecoveredSignature {
    /// Name of the function.
    pub name: String,
    /// List of recovered arguments.
    pub args: Vec<RecoveredArg>,
    /// If `true`, there was an argument that was marked as partial.
    pub partial: bool,
    /// If `true`, there was an error reading the argument info.
    pub error: bool,
}

impl RecoveredSignature {
    const ARGINFO_ENDSEQ: u16 = 0xff;
    const ARGINFO_STARTAGG: u16 = 0xfe;
    const ARGINFO_ENDAGG: u16 = 0xfd;
    const ARGINFO_DOTDOTDOT: u16 = 0xfc;
    const ARGINFO_OFFSET_TOOLARGE: u16 = 0xfb;

    /// Reads the `FUNCDATA_ArgInfo` table for `func_data` and builds the recovered signature.
    pub fn read(
        func_data: &GoFuncData,
        go_binary: &dyn GoRttiMapper,
    ) -> std::io::Result<RecoveredSignature> {
        let args = Self::read_args(func_data, go_binary)?;
        Ok(RecoveredSignature {
            name: func_data.get_name(),
            partial: args.has_partial_flag(),
            error: args.partial,
            args: args.sub_args.unwrap_or_default(),
        })
    }

    /// Reads the `FUNCDATA_ArgInfo` byte sequence into a single aggregate [`RecoveredArg`] whose
    /// `sub_args` are the top-level arguments.
    ///
    /// Java tracks the nested argument lists by reference; here they live in `lists` and are
    /// referred to by index, which reproduces Java's aliasing exactly, including the fact that
    /// `parent` is restored from a stack of *child* lists (so aggregates nested more than one
    /// level deep are dropped rather than attached to their grandparent).
    pub fn read_args(
        func_data: &GoFuncData,
        go_binary: &dyn GoRttiMapper,
    ) -> std::io::Result<RecoveredArg> {
        let arg_info_offset = func_data.get_func_data_value(GoFuncDataTable::ArgInfo)?;
        if arg_info_offset == -1 {
            return Ok(RecoveredArg { sub_args: Some(Vec::new()), arg_size: 0, partial: false });
        }
        let mut arg_info_reader = go_binary.get_reader(arg_info_offset);

        let mut lists: Vec<Vec<RecoveredArg>> = vec![Vec::new()];
        const RESULTS: usize = 0;
        let mut result_stack: Vec<usize> = Vec::new();
        let mut parent: Option<usize> = None;
        let mut current: usize = RESULTS;

        let finish = |lists: &mut Vec<Vec<RecoveredArg>>, error: bool| RecoveredArg {
            sub_args: Some(std::mem::take(&mut lists[RESULTS])),
            arg_size: 0,
            partial: error,
        };

        loop {
            let b = match arg_info_reader.read_next_unsigned_byte() {
                Ok(b) => b,
                // error flag
                Err(_) => return Ok(finish(&mut lists, true)),
            };
            match b {
                Self::ARGINFO_ENDSEQ => return Ok(finish(&mut lists, false)),
                Self::ARGINFO_STARTAGG => {
                    parent = Some(current);
                    lists.push(Vec::new());
                    current = lists.len() - 1;
                    result_stack.push(current);
                }
                Self::ARGINFO_ENDAGG => {
                    let Some(parent_idx) = parent else {
                        return Err(std::io::Error::new(
                            std::io::ErrorKind::InvalidData,
                            "no parent",
                        ));
                    };
                    let sub_args = std::mem::take(&mut lists[current]);
                    lists[parent_idx].push(RecoveredArg {
                        sub_args: Some(sub_args),
                        arg_size: 0,
                        partial: false,
                    });
                    current = parent_idx;
                    parent = result_stack.pop();
                }
                Self::ARGINFO_DOTDOTDOT => {
                    lists[current].push(RecoveredArg {
                        sub_args: None,
                        arg_size: -1,
                        partial: true,
                    });
                }
                Self::ARGINFO_OFFSET_TOOLARGE => {
                    lists[current].push(RecoveredArg {
                        sub_args: None,
                        arg_size: -2,
                        partial: true,
                    });
                }
                _ => {
                    // b == 'offset', but value doesn't seem to be consistently useful
                    let sz = match arg_info_reader.read_next_unsigned_byte() {
                        Ok(sz) => sz,
                        Err(_) => return Ok(finish(&mut lists, true)),
                    };
                    lists[current].push(RecoveredArg {
                        sub_args: None,
                        arg_size: sz as i32,
                        partial: false,
                    });
                }
            }
        }
    }
}

impl std::fmt::Display for RecoveredSignature {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let mut sb = String::new();
        if self.partial {
            sb.push_str("[partial] ");
        }
        if self.error {
            sb.push_str("[error] ");
        }

        sb.push_str("func ");
        sb.push_str(&self.name);
        sb.push('(');

        for (i, arg) in self.args.iter().enumerate() {
            if i != 0 {
                sb.push_str(", ");
            }
            arg.concat_string(&mut sb);
        }

        sb.push_str(") ???");

        f.write_str(&sb)
    }
}

