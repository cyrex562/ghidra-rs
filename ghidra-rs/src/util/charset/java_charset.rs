    /// `cs.encode(...)` / `cs.newEncoder().encode(...)`, as printed by the JDK.
    #[test]
    fn encoders_match_jdk() {
        let u = |s: &str| s.encode_utf16().collect::<Vec<u16>>();
        assert_eq!(JavaCharset::UTF_16.encode_units(&u("A")).unwrap(), vec![0xFE, 0xFF, 0x00, 0x41]);
        assert_eq!(JavaCharset::UTF_16.encode_units(&[]).unwrap(), Vec::<u8>::new());
        assert_eq!(JavaCharset::UTF_32.encode_units(&u("A")).unwrap(), vec![0, 0, 0, 0x41]);
        assert_eq!(JavaCharset::UTF_16LE.encode_units(&u("A\u{FEFF}")).unwrap(), vec![0x41, 0, 0xFF, 0xFE]);
        assert_eq!(JavaCharset::UTF_32LE.encode_units(&u("A")).unwrap(), vec![0x41, 0, 0, 0]);
        assert_eq!(JavaCharset::UTF_8.encode_units_replacing(&[0x41, 0xD800, 0x42]), vec![0x41, 0x3F, 0x42]);
        assert_eq!(JavaCharset::UTF_8.encode_units(&[0x41, 0xD800, 0x42]), Err(CharacterCodingException::Malformed(1)));
        assert_eq!(JavaCharset::UTF_16BE.encode_units_replacing(&[0xD800]), vec![0xFF, 0xFD]);
        assert_eq!(JavaCharset::UTF_32BE.encode_units_replacing(&[0xD800]), vec![0, 0, 0xFF, 0xFD]);
        let ascii = JavaCharset::us_ascii();
        assert_eq!(ascii.encode_units_replacing(&u("A\u{e9}")), vec![0x41, 0x3F]);
        assert_eq!(ascii.encode_units(&u("A\u{e9}")), Err(CharacterCodingException::Unmappable(1)));
        assert_eq!(JavaCharset::iso_8859_1().encode_units_replacing(&u("\u{20ac}")), vec![0x3F]);
        assert_eq!(JavaCharset::for_name("windows-1252").unwrap().encode_str("\u{20ac}").unwrap(), vec![0x80]);
        assert_eq!(JavaCharset::UTF_8.encode_str("\u{1F600}").unwrap(), vec![0xF0, 0x9F, 0x98, 0x80]);
        // IBM-Thai: U+0E48 decodes from both 0x51 and 0xED; the JDK encoder picks 0xED.
        let thai = JavaCharset::for_name("IBM-Thai").unwrap();
        assert_eq!(thai.encode_str("\u{0E48}[").unwrap(), vec![0xED, 73]);
        assert!(thai.can_encode('['));
        assert!(!thai.can_encode('\u{20ac}'));
    }

