    /// Runs the decode loop `StringRenderBuilder.decodeBytesUsingCharset` uses and records what
    /// the JDK probe printed: each decoded char as `U+XXXX`, each error as `ERRnm` (malformed) or
    /// `ERRnu` (unmappable).
    fn trace(name: &str, bytes: &[u8]) -> String {
        let cs = JavaCharset::for_name(name).unwrap();
        let mut decoder = cs.new_decoder();
        let mut pos = 0;
        let mut out = Vec::new();
        let mut parts = Vec::new();
        while pos < bytes.len() {
            out.clear();
            let r = decoder.decode(bytes, &mut pos, &mut out);
            parts.extend(out.iter().map(|c| format!("U+{c:04X}")));
            match r {
                CoderResult::Malformed(n) => {
                    parts.push(format!("ERR{n}m"));
                    pos += n;
                }
                CoderResult::Unmappable(n) => {
                    parts.push(format!("ERR{n}u"));
                    pos += n;
                }
                CoderResult::Underflow => {}
            }
        }
        parts.join(" ")
    }

