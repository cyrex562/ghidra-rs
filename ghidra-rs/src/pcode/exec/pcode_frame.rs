    fn branch_to_exactly_past_last_op_is_fall_through() {
        let s = spaces();
        let mut f = frame(&s, vec![copy_op(&s, 0x1000), copy_op(&s, 0x1001)], HashMap::new());
        f.advance(); // index = 1

        // Java allows index == code.size(); that's fall-through, not an error.
        f.branch(2).unwrap();
        assert_eq!(f.index(), 2);
        assert!(f.is_fall_through());
        assert!(f.is_finished());
    }

    #[test]
    fn finish_as_branch_records_last_op_and_marks_branch() {
        let s = spaces();
        let mut f = frame(&s, vec![copy_op(&s, 0x1000), copy_op(&s, 0x1001)], HashMap::new());

        f.advance();
        f.advance(); // index = 2, we are "executing" op 1
        f.finish_as_branch();

        assert_eq!(f.branched(), 1);
        assert_eq!(f.index(), -1);
        assert!(f.is_branch());
        assert!(f.is_finished());
        assert!(!f.is_fall_through());
    }

    #[test]
    fn userop_names_fall_back_to_the_frame_map() {
        let s = spaces();
        let f = frame(&s, Vec::new(), HashMap::from([(3, "frame_op".to_string())]));

        assert_eq!(f.get_userop_name(3), Some("frame_op"));
        assert_eq!(f.get_userop_name(4), None);
        assert_eq!(f.userop_names().len(), 1);
    }

    #[test]
    fn copy_code_is_a_shallow_copy() {
        let s = spaces();
        let f = frame(&s, vec![copy_op(&s, 0x1000)], HashMap::new());

        let copied = f.copy_code();
        assert_eq!(copied.len(), 1);
        assert_eq!(copied[0], f.code()[0]);
    }

    #[test]
    fn to_string_marks_the_current_index() {
        let s = spaces();
        let f = frame(&s, vec![copy_op(&s, 0x1000)], HashMap::new());

        assert_eq!(
            f.to_string(),
            "<p-code frame: index=0 {\n -> *[ram]0x14:1 = COPY *[ram]0x10:1\n}>"
        );
    }

    #[test]
    fn to_string_notes_fall_through_once_past_the_end() {
        let s = spaces();
        let mut f = frame(&s, vec![copy_op(&s, 0x1000)], HashMap::new());
        f.advance();

        // The op is no longer marked (index 1 != op 0), and fall-through is announced.
        assert_eq!(
            f.to_string(),
            "<p-code frame: index=1 {\n    *[ram]0x14:1 = COPY *[ram]0x10:1\n *> fall-through\n}>"
        );
    }

    #[test]
    fn to_string_marks_the_branched_op() {
        let s = spaces();
        let mut f = frame(&s, vec![copy_op(&s, 0x1000), copy_op(&s, 0x1001)], HashMap::new());
        f.advance();
        f.finish_as_branch();

        assert_eq!(
            f.to_string(),
            concat!(
                "<p-code frame: index=-1 branched=0 {\n",
                " *> *[ram]0x14:1 = COPY *[ram]0x10:1\n",
                "    *[ram]0x14:1 = COPY *[ram]0x10:1\n",
                "}>"
            )
        );
    }

    #[test]
    fn to_string_resolves_callother_via_the_frame_userop_map() {
        let s = spaces();
        let callother = PcodeOp::new(
            OpCode::CallOther,
            SequenceNumber::new(Address::new(s.ram.clone(), 0x1000), 0),
            vec![Varnode::new(Address::new(s.constant.clone(), 7), 4)],
            None,
        );
        let f = frame(&s, vec![callother], HashMap::from([(7, "frame_op".to_string())]));

        // Userop 7 is unknown to the language, so the name comes from the frame's map.
        assert_eq!(f.to_string(), "<p-code frame: index=0 {\n -> CALLOTHER \"frame_op\"\n}>");
    }
