//! Port of `ghidra.features.bsim.query.description.VectorResult`.

use std::io::{self, Write};

use crate::generic::lsh::vector::{LSHVector, LSHVectorFactory};
use crate::util::xml::spec_xml_utils;
use crate::util::xml::xml_element::XmlElement;
use crate::util::xml::xml_pull_parser::XmlPullParser;

/// A vector recovered from a BSim database query, together with its similarity/significance
/// scores and how many functions instantiate it.
///
/// Port of `ghidra.features.bsim.query.description.VectorResult`.
///
/// Every field is `pub`, matching the Java class (which has no accessors -- callers read and
/// write the fields directly).
///
/// Generic over the concrete [`LSHVector`] implementation for the same reason as
/// [`SignatureRecord`](super::SignatureRecord): [`LSHVector`] is not object safe, so a type
/// parameter stands in for `dyn LSHVector`.
///
/// `vec` is `Option<V>` rather than a bare `V`, matching the Java field's nullability: the
/// no-arg constructor ([`VectorResult::empty`]) leaves it unset, and [`restore_xml`](Self::restore_xml)
/// only populates it when the XML stream actually carries a vector element.
#[derive(Debug, Clone)]
pub struct VectorResult<V: LSHVector> {
    /// Id of vector.
    pub vectorid: i64,
    /// Similarity score.
    pub sim: f64,
    /// Significance score.
    pub signif: f64,
    /// Number of duplicate results.
    pub hitcount: i32,
    pub vec: Option<V>,
}

impl<V: LSHVector> VectorResult<V> {
    /// Java: `VectorResult()`.
    pub fn empty() -> Self {
        Self { vectorid: 0, sim: 0.0, signif: 0.0, hitcount: 0, vec: None }
    }

    /// Java: `VectorResult(long vid, int cnt, double sm, double sg, LSHVector v)`.
    pub fn new(vid: i64, cnt: i32, sm: f64, sg: f64, v: V) -> Self {
        Self { vectorid: vid, sim: sm, signif: sg, hitcount: cnt, vec: Some(v) }
    }

    /// Java: `saveXml(Writer)`.
    pub fn save_xml<W: Write>(&self, write: &mut W) -> io::Result<()> {
        let mut buf = String::new();
        buf.push_str("<vec");
        spec_xml_utils::encode_unsigned_integer_attribute(&mut buf, "id", self.vectorid);
        buf.push_str(">\n");
        buf.push_str(" <hit>");
        buf.push_str(&self.hitcount.to_string());
        buf.push_str("</hit>\n");
        buf.push_str(" <sim>");
        buf.push_str(&self.sim.to_string());
        buf.push_str("</sim>\n");
        buf.push_str(" <sig>");
        buf.push_str(&self.signif.to_string());
        buf.push_str("</sig>\n");
        write.write_all(buf.as_bytes())?;
        if let Some(vec) = &self.vec {
            vec.save_xml(write)?;
        }
        write.write_all(b"</vec>\n")
    }

    /// Java: `restoreXml(XmlPullParser, LSHVectorFactory)`.
    ///
    /// # Errors
    /// If the XML stream is malformed (missing/mismatched `<vec>`/`<hit>`/`<sim>`/`<sig>` tags).
    pub fn restore_xml<P, F>(
        &mut self,
        parser: &mut P,
        vector_factory: &F,
    ) -> Result<(), crate::util::xml::xml_exception::XmlException>
    where
        P: XmlPullParser,
        F: LSHVectorFactory<Vector = V>,
    {
        let el = parser.start(&["vec"])?;
        self.vectorid = spec_xml_utils::decode_long(el.get_attribute("id").as_deref());
        parser.start(&["hit"])?;
        self.hitcount = spec_xml_utils::decode_int(Some(parser.end()?.get_text()));
        parser.start(&["sim"])?;
        self.sim = parse_double(&parser.end()?)?;
        parser.start(&["sig"])?;
        self.signif = parse_double(&parser.end()?)?;
        if parser.peek().is_start() {
            self.vec = Some(vector_factory.restore_vector_from_xml(parser));
        }
        parser.end()?;
        Ok(())
    }
}

/// Java: `Double.parseDouble(...)`, which throws an unchecked `NumberFormatException` on
/// malformed input; the ported call sites are all checked (`restore_xml` returns a `Result`), so
/// this surfaces the same failure as an [`XmlException`] instead of panicking. Mirrors
/// `weight_factory::parse_text`'s handling of the same Java idiom.
fn parse_double<E: crate::util::xml::xml_element::XmlElement>(
    el: &E,
) -> Result<f64, crate::util::xml::xml_exception::XmlException> {
    let text = el.get_text();
    text.parse()
        .map_err(|_| crate::util::xml::xml_exception::XmlException::with_message(format!("bad numeric text: {}", text)))
}

impl<V: LSHVector + PartialEq> PartialEq for VectorResult<V> {
    /// Java: `equals(Object)` (generated by Eclipse), comparing every field. `sim`/`signif` are
    /// compared by bit pattern (`Double.doubleToLongBits`), matching the established convention
    /// in this crate (see e.g. `VtScore`'s `PartialEq`) rather than IEEE `==`.
    fn eq(&self, other: &Self) -> bool {
        self.hitcount == other.hitcount
            && self.signif.to_bits() == other.signif.to_bits()
            && self.sim.to_bits() == other.sim.to_bits()
            && self.vec == other.vec
            && self.vectorid == other.vectorid
    }
}

impl<V: LSHVector + Eq> Eq for VectorResult<V> {}

impl<V: LSHVector + std::hash::Hash> std::hash::Hash for VectorResult<V> {
    /// Java: `hashCode()` (generated by Eclipse), `Objects.hash(hitcount, signif, sim, vec,
    /// vectorid)`.
    fn hash<H: std::hash::Hasher>(&self, state: &mut H) {
        self.hitcount.hash(state);
        self.signif.to_bits().hash(state);
        self.sim.to_bits().hash(state);
        self.vec.hash(state);
        self.vectorid.hash(state);
    }
}

