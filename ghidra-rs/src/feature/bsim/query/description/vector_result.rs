    #[test]
    fn equals_compares_every_field() {
        let a = VectorResult::new(1, 2, 3.0, 4.0, MockVector { tag: 5 });
        let b = VectorResult::new(1, 2, 3.0, 4.0, MockVector { tag: 5 });
        assert_eq!(a, b);
    }

    #[test]
    fn equals_differs_on_vectorid_alone() {
        // Unlike a hypothetical "id-only" equality, every field participates: two results with
        // the same vector id but different hitcount are NOT equal.
        let a = VectorResult::new(1, 2, 3.0, 4.0, MockVector { tag: 5 });
        let b = VectorResult::new(1, 9, 3.0, 4.0, MockVector { tag: 5 });
        assert_ne!(a, b);
    }
