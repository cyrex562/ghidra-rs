    // --- restore_xml ---

    struct VecParser {
        elements: Vec<XmlElementImpl>,
        pos: usize,
    }

    impl XmlPullParser for VecParser {
        type Element = XmlElementImpl;
        fn get_name(&self) -> &str {
            "VecParser"
        }
        fn get_processing_instruction(&self, _name: &str, _attribute: &str) -> Option<String> {
            None
        }
        fn is_pulling_content(&self) -> bool {
            true
        }
        fn set_pulling_content(&mut self, _pulling_content: bool) {}
        fn has_next(&self) -> bool {
            self.pos < self.elements.len()
        }
        fn peek(&self) -> Self::Element {
            self.elements[self.pos].clone()
        }
        fn next(&mut self) -> Self::Element {
            let el = self.elements[self.pos].clone();
            self.pos += 1;
            el
        }
        fn start(&mut self, names: &[&str]) -> Result<Self::Element, XmlException> {
            let elem = self.next();
            if !elem.is_start() {
                return Err(XmlException::with_message("expected start element"));
            }
            if !names.is_empty() && !names.iter().any(|n| *n == elem.get_name()) {
                return Err(XmlException::with_message("unexpected start element name"));
            }
            Ok(elem)
        }
        fn end(&mut self) -> Result<Self::Element, XmlException> {
            let elem = self.next();
            if !elem.is_end() {
                return Err(XmlException::with_message("expected end element"));
            }
            Ok(elem)
        }
        fn dispose(&mut self) {}
    }

    fn start_attr(name: &str, attr: &str, value: &str) -> XmlElementImpl {
        XmlElementImpl::new(
            true,
            false,
            name,
            0,
            vec![(attr.to_string(), value.to_string())],
            None,
            0,
            0,
        )
        .unwrap()
    }

    fn start(name: &str) -> XmlElementImpl {
        XmlElementImpl::new(true, false, name, 0, Vec::new(), None, 0, 0).unwrap()
    }

    fn end_with_text(name: &str, text: &str) -> XmlElementImpl {
        XmlElementImpl::new(false, true, name, 0, Vec::new(), Some(text.to_string()), 0, 0)
            .unwrap()
    }

    fn end(name: &str) -> XmlElementImpl {
        XmlElementImpl::new(false, true, name, 0, Vec::new(), Some(String::new()), 0, 0).unwrap()
    }

    #[test]
    fn restore_xml_reads_scalars_without_a_vector_element() {
        let mut parser = VecParser {
            elements: vec![
                start_attr("vec", "id", "0xff"),
                start("hit"),
                end_with_text("hit", "4"),
                start("sim"),
                end_with_text("sim", "1.5"),
                start("sig"),
                end_with_text("sig", "2.5"),
                end("vec"),
            ],
            pos: 0,
        };
        let factory = MockFactory::default();
        let mut vr: VectorResult<MockVector> = VectorResult::empty();
        vr.restore_xml(&mut parser, &factory).unwrap();
        assert_eq!(vr.vectorid, 0xff);
        assert_eq!(vr.hitcount, 4);
        assert_eq!(vr.sim, 1.5);
        assert_eq!(vr.signif, 2.5);
        assert!(vr.vec.is_none());
        assert!(!parser.has_next());
    }

    #[test]
    fn restore_xml_populates_the_vector_when_present() {
        let mut parser = VecParser {
            elements: vec![
                start_attr("vec", "id", "0x2"),
                start("hit"),
                end_with_text("hit", "1"),
                start("sim"),
                end_with_text("sim", "0.1"),
                start("sig"),
                end_with_text("sig", "0.2"),
                start("mockvec"), // any nested start element signals a vector is present
                end("mockvec"),
                end("vec"),
            ],
            pos: 0,
        };
        let factory = MockFactory { base: LSHVectorFactoryBase::default(), next_tag: 42 };
        let mut vr: VectorResult<MockVector> = VectorResult::empty();
        vr.restore_xml(&mut parser, &factory).unwrap();
        assert_eq!(vr.vec, Some(MockVector { tag: 42 }));
    }

    #[test]
    fn round_trip_save_then_restore() {
        let original = VectorResult::new(0x10, 6, 3.0, 4.0, MockVector { tag: 1 });
        let mut buf = Vec::new();
        original.save_xml(&mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();

        // Re-tokenize the saved text into the same element stream shape `restore_xml` expects.
        let mut parser = VecParser {
            elements: vec![
                start_attr("vec", "id", "0x10"),
                start("hit"),
                end_with_text("hit", "6"),
                start("sim"),
                end_with_text("sim", "3"),
                start("sig"),
                end_with_text("sig", "4"),
                start("mockvec"),
                end("mockvec"),
                end("vec"),
            ],
            pos: 0,
        };
        assert!(text.contains("<mockvec tag=\"1\"/>"));
        let factory = MockFactory { base: LSHVectorFactoryBase::default(), next_tag: 1 };
        let mut restored: VectorResult<MockVector> = VectorResult::empty();
        restored.restore_xml(&mut parser, &factory).unwrap();
        assert_eq!(restored.vectorid, original.vectorid);
        assert_eq!(restored.hitcount, original.hitcount);
        assert_eq!(restored.vec, original.vec);
    }

